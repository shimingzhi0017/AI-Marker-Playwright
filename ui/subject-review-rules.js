export function isValidTaskType(subject, taskType) {
  return !taskType || Boolean(subject && Object.hasOwn(subjectTaskTypes[subject] || {}, taskType));
}

export function taskTypePolicy(subject, taskType) {
  return (subject && taskType && subjectTaskTypes[subject]?.[taskType]?.guidance) || '';
}
